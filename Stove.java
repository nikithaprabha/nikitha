class Stove{
 //instance variable
 String brand;
 String burner;  
 String type;

 //no args constructor
 Stove(){
 System.out.println("Stove constructor is invoked");
 }


 //parameterized constructor
 Stove(String brand, String burner , String type){
 this.brand = brand;
 this.burner=burner;
 this.type=type;
 
 
 }
 











}